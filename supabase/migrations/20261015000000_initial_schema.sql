-- Initial schema for the Funding Scan Platform.
--
-- Every intake channel (federal APIs, email, web research) writes the same row
-- shape into `opportunities`. Row-Level Security limits each signed-in user to
-- the organizations they own; background jobs use the service role.

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- organizations: one per customer
-- ---------------------------------------------------------------------------

create table public.organizations (
  id             uuid primary key default gen_random_uuid(),
  owner_user_id  uuid not null references auth.users (id) on delete cascade,
  name           text not null,
  slug           text not null,
  -- Postmark inbox, {slug}-{6 random chars}@{INBOUND_DOMAIN}. Generated by app
  -- code on creation (Phase 4); null until then.
  inbox_address  text unique,
  plan           text not null default 'free',
  digest_day     smallint not null default 1 check (digest_day between 0 and 6),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index organizations_owner_idx on public.organizations (owner_user_id);

create trigger organizations_updated_at
  before update on public.organizations
  for each row execute function public.set_updated_at();

-- True when the signed-in user owns the organization. SECURITY DEFINER so RLS
-- policies on other tables can call it without recursing into organizations' RLS.
create or replace function public.is_org_owner(org_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.organizations o
    where o.id = org_id and o.owner_user_id = auth.uid()
  );
$$;

-- ---------------------------------------------------------------------------
-- profiles: versioned scan input; a new row on every save
-- ---------------------------------------------------------------------------

create table public.profiles (
  id               uuid primary key default gen_random_uuid(),
  organization_id  uuid not null references public.organizations (id) on delete cascade,
  version          integer not null,
  -- The form fields from prompts/research-scan.md section 1 (org_name,
  -- industry, org_type, parent_org, service_area, ...).
  fields           jsonb not null,
  naics_codes      text[] not null default '{}',
  states           text[] not null default '{}',
  keywords         text[] not null default '{}',
  created_by       uuid default auth.uid() references auth.users (id) on delete set null,
  created_at       timestamptz not null default now(),
  unique (organization_id, version)
);

-- Assign the next version number per organization on insert.
create or replace function public.set_profile_version()
returns trigger
language plpgsql
as $$
begin
  select coalesce(max(version), 0) + 1 into new.version
  from public.profiles
  where organization_id = new.organization_id;
  return new;
end;
$$;

create trigger profiles_set_version
  before insert on public.profiles
  for each row execute function public.set_profile_version();

-- ---------------------------------------------------------------------------
-- scan_runs: cost and audit log, one row per job execution
-- ---------------------------------------------------------------------------

create table public.scan_runs (
  id                  uuid primary key default gen_random_uuid(),
  organization_id     uuid not null references public.organizations (id) on delete cascade,
  channel             text not null check (channel in (
                        'api_sam', 'api_grants', 'email', 'research',
                        'assess', 'reverify', 'digest', 'subscriptions')),
  status              text not null default 'running' check (status in (
                        'queued', 'running', 'succeeded', 'partial', 'failed')),
  started_at          timestamptz not null default now(),
  finished_at         timestamptz,
  items_found         integer not null default 0,
  claude_calls        integer not null default 0,
  tokens_in           bigint not null default 0,
  tokens_out          bigint not null default 0,
  cache_read_tokens   bigint not null default 0,
  cache_write_tokens  bigint not null default 0,
  searches            integer not null default 0,
  cost_usd            numeric(12, 6) not null default 0,
  error               text,
  -- Raw API responses, search_plan_used, etc., so runs can be replayed.
  raw                 jsonb
);

create index scan_runs_org_started_idx on public.scan_runs (organization_id, started_at desc);

-- Atomically add one Claude call's usage to a scan run. Called only by
-- lib/claude.ts with the service role. Returns false if the run doesn't exist.
create or replace function public.record_claude_usage(
  p_scan_run_id         uuid,
  p_tokens_in           bigint,
  p_tokens_out          bigint,
  p_cache_read_tokens   bigint,
  p_cache_write_tokens  bigint,
  p_searches            integer,
  p_cost_usd            numeric
)
returns boolean
language plpgsql
set search_path = ''
as $$
begin
  update public.scan_runs set
    claude_calls       = claude_calls + 1,
    tokens_in          = tokens_in + p_tokens_in,
    tokens_out         = tokens_out + p_tokens_out,
    cache_read_tokens  = cache_read_tokens + p_cache_read_tokens,
    cache_write_tokens = cache_write_tokens + p_cache_write_tokens,
    searches           = searches + p_searches,
    cost_usd           = cost_usd + p_cost_usd
  where id = p_scan_run_id;
  return found;
end;
$$;

revoke execute on function public.record_claude_usage(uuid, bigint, bigint, bigint, bigint, integer, numeric)
  from public, anon, authenticated;
grant execute on function public.record_claude_usage(uuid, bigint, bigint, bigint, bigint, integer, numeric)
  to service_role;

-- ---------------------------------------------------------------------------
-- opportunities: the single table every channel writes to
-- ---------------------------------------------------------------------------

create table public.opportunities (
  id                        uuid primary key default gen_random_uuid(),
  organization_id           uuid not null references public.organizations (id) on delete cascade,
  source_channel            text not null check (source_channel in ('api_sam', 'api_grants', 'email', 'research')),
  -- SAM noticeId, Grants.gov id, hash of (link or name + deadline) for email,
  -- normalized official_link for research.
  external_id               text not null,

  name                      text not null,
  funder                    text,
  funder_type               text,
  opportunity_type          text,
  category                  text,
  match_basis               text,
  -- e.g. Open - Fixed Deadline, Open - Rolling, Forecasted, Closed - Recurring,
  -- Closed, Closed - Expired, Link Broken, Not eligible.
  status                    text,
  last_round                text,
  deadline                  date,
  -- Only when the source states a time of day.
  deadline_at               timestamptz,
  -- As stated by the funder, or 'Not stated'.
  award_amount              text,
  official_link             text not null,
  opportunity_id            text,
  synopsis                  text,
  contact                   text,

  -- Scoring fields written by lib/assess.ts.
  eligibility               jsonb,
  state_requirement         text,
  fit                       text,
  priority                  text check (priority in ('High', 'Medium', 'Low')),
  relevance                 smallint check (relevance between 0 and 100),
  compliance_flag           text,
  assessed_at               timestamptz,

  verification              text not null default 'Needs Verification'
                              check (verification in ('Verified - Official Source', 'Needs Verification')),
  verify_notes              text,

  -- For status = 'Not eligible' rows.
  disqualifying_rule        text,
  could_become_eligible_if  text,

  -- Staff-owned. Set to 'New' on insert and never written by automated code;
  -- see protect_opportunity_fields() below.
  pursuit_status            text not null default 'New'
                              check (pursuit_status in ('New', 'Reviewing', 'Pursuing', 'Applied', 'Not a Fit')),

  first_seen                timestamptz not null default now(),
  last_verified             timestamptz,
  raw                       jsonb,
  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now(),

  unique (organization_id, source_channel, external_id)
);

create index opportunities_org_deadline_idx on public.opportunities (organization_id, deadline);
create index opportunities_org_relevance_idx on public.opportunities (organization_id, relevance desc);
create index opportunities_org_status_idx on public.opportunities (organization_id, status);

create trigger opportunities_updated_at
  before update on public.opportunities
  for each row execute function public.set_updated_at();

-- Database-level backstop for two rules in CLAUDE.md, so a bug in an upsert
-- cannot break them:
--   * first_seen is never overwritten.
--   * pursuit_status is staff-owned: automated code (the service role) always
--     inserts 'New' and can never change it afterwards.
create or replace function public.protect_opportunity_fields()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' then
    if current_user = 'service_role' then
      new.pursuit_status := 'New';
    end if;
    return new;
  end if;

  new.first_seen := old.first_seen;
  if current_user = 'service_role' then
    new.pursuit_status := old.pursuit_status;
  end if;
  return new;
end;
$$;

create trigger opportunities_protect_fields
  before insert or update on public.opportunities
  for each row execute function public.protect_opportunity_fields();

-- ---------------------------------------------------------------------------
