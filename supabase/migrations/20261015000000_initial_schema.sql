-- ---------------------------------------------------------------------------
-- manual_checks: sources that could not be read, kept across runs
-- ---------------------------------------------------------------------------

create table public.manual_checks (
  id               uuid primary key default gen_random_uuid(),
  organization_id  uuid not null references public.organizations (id) on delete cascade,
  source           text not null,
  url              text not null,
  reason           text not null,
  resolved         boolean not null default false,
  resolved_at      timestamptz,
  first_seen       timestamptz not null default now(),
  last_seen        timestamptz not null default now(),
  scan_run_id      uuid references public.scan_runs (id) on delete set null,
  unique (organization_id, url)
);

-- ---------------------------------------------------------------------------
-- Row-Level Security
--
-- Rule: a user can read and write only rows whose organization_id belongs to
-- an organization they own. The service role (Inngest functions, API routes)
-- bypasses RLS. On top of RLS, column grants narrow what signed-in users may
-- change: data written by the intake channels is read-only to them.
-- ---------------------------------------------------------------------------

alter table public.organizations       enable row level security;
alter table public.profiles            enable row level security;
alter table public.scan_runs           enable row level security;
alter table public.opportunities       enable row level security;
alter table public.emails              enable row level security;
alter table public.email_subscriptions enable row level security;
alter table public.manual_checks       enable row level security;

-- Signed-out visitors get nothing.
revoke all on public.organizations, public.profiles, public.scan_runs, public.opportunities,
  public.emails, public.email_subscriptions, public.manual_checks from anon;

-- organizations
create policy "owners read their organizations" on public.organizations
  for select to authenticated using (owner_user_id = auth.uid());
create policy "users create organizations they own" on public.organizations
  for insert to authenticated with check (owner_user_id = auth.uid());
create policy "owners update their organizations" on public.organizations
  for update to authenticated using (owner_user_id = auth.uid()) with check (owner_user_id = auth.uid());
create policy "owners delete their organizations" on public.organizations
  for delete to authenticated using (owner_user_id = auth.uid());
-- inbox_address and plan are set by the server, not the user.
revoke update on public.organizations from authenticated;
grant update (name, slug, digest_day) on public.organizations to authenticated;

-- profiles: append-only versions
create policy "owners read profiles" on public.profiles
  for select to authenticated using (public.is_org_owner(organization_id));
create policy "owners add profile versions" on public.profiles
  for insert to authenticated with check (public.is_org_owner(organization_id));
revoke update, delete on public.profiles from authenticated;

-- scan_runs: read-only to users
create policy "owners read scan runs" on public.scan_runs
  for select to authenticated using (public.is_org_owner(organization_id));
revoke insert, update, delete on public.scan_runs from authenticated;

-- opportunities: users read their rows and change only pursuit_status
create policy "owners read opportunities" on public.opportunities
  for select to authenticated using (public.is_org_owner(organization_id));
create policy "owners update opportunities" on public.opportunities
  for update to authenticated
  using (public.is_org_owner(organization_id))
  with check (public.is_org_owner(organization_id));
revoke insert, update, delete on public.opportunities from authenticated;
grant update (pursuit_status) on public.opportunities to authenticated;

-- emails: read-only to users
create policy "owners read emails" on public.emails
  for select to authenticated using (public.is_org_owner(organization_id));
revoke insert, update, delete on public.emails from authenticated;

-- email_subscriptions: users mark items done
create policy "owners read subscriptions" on public.email_subscriptions
  for select to authenticated using (public.is_org_owner(organization_id));
create policy "owners update subscriptions" on public.email_subscriptions
  for update to authenticated
  using (public.is_org_owner(organization_id))
  with check (public.is_org_owner(organization_id));
revoke insert, update, delete on public.email_subscriptions from authenticated;
grant update (status) on public.email_subscriptions to authenticated;

-- manual_checks: users mark items resolved
create policy "owners read manual checks" on public.manual_checks
  for select to authenticated using (public.is_org_owner(organization_id));
create policy "owners update manual checks" on public.manual_checks
  for update to authenticated
  using (public.is_org_owner(organization_id))
  with check (public.is_org_owner(organization_id));
revoke insert, update, delete on public.manual_checks from authenticated;
grant update (resolved, resolved_at) on public.manual_checks to authenticated;
